import os
import json
import pandas as pd
import re

# Prevent execution timeout loops on local hardware
os.environ["DEEPEVAL_DISABLE_TIMEOUTS"] = "1"
os.environ["DEEPEVAL_PER_TASK_TIMEOUT_SECONDS_OVERRIDE"] = "1200"
os.environ["DEEPEVAL_PER_ATTEMPT_TIMEOUT_SECONDS_OVERRIDE"] = "1200"

from deepeval.synthesizer import Synthesizer
from deepeval.synthesizer.config import EvolutionConfig
from deepeval.synthesizer.types import Evolution
from deepeval.models import OllamaModel, GPTModel

# 1. Instantiate native local Ollama model hook
adversarial_builder_model = GPTModel(model="gpt-4o")
# adversarial_builder_model = OllamaModel(model="llama3.2:latest")  # Use Ollama for local model evaluation

# 2. Provide baseline context blocks
reference_contexts = [
    ["Paris is the capital city of France, situated along the Seine River."],
    [
        "Gold is a heavy, soft, malleable, and ductile metal with the chemical symbol Au."
    ],
]

print("🛡️ Generating complex prompt datasets via openai gpt-4o context evolution...")

# 3. Instantiate the EvolutionConfig weighting complexity variations
evolution_config = EvolutionConfig(
    num_evolutions=1,  # Reduced to 1 to help smaller local models follow instructions better
    evolutions={
        Evolution.REASONING: 0.34,
        Evolution.CONSTRAINED: 0.33,
        Evolution.HYPOTHETICAL: 0.33,
    },
)

# 4. Instantiate Synthesizer
synthesizer = Synthesizer(
    model=adversarial_builder_model, evolution_config=evolution_config
)

# 5. Run Generation Pipeline
generated_goldens = synthesizer.generate_goldens_from_contexts(
    contexts=reference_contexts, max_goldens_per_context=3
)


def clean_extracted_text(text: str) -> str:
    """Isolates and extracts the final query from variable LLM formats."""
    text = str(text).strip()

    # 1. Catch inline "The rewritten input is: [Question]" patterns
    inline_match = re.search(r"The rewritten input is\s*:\s*(.*)", text, re.IGNORECASE)
    if inline_match:
        extracted = inline_match.group(1).strip()
        return extracted.strip('"').strip("'").strip()

    # 2. Direct Multi-line "Rewritten Input:" extraction pattern
    rewritten_match = re.search(
        r"(?:Rewritten Input|rewritten input could be)\s*:\s*(.*)",
        text,
        re.IGNORECASE | re.DOTALL,
    )
    if rewritten_match:
        extracted = rewritten_match.group(1).strip()
        lines = [line.strip() for line in extracted.split("\n") if line.strip()]
        if lines:
            return lines[0].strip('"').strip("'").strip()

    # 3. Extract everything following the colon if generic conversational intro text is detected
    if ":" in text and any(
        phrase in text.lower() for phrase in ["rewritten input", "follows", "could be"]
    ):
        parts = text.split(":", 1)
        extracted = parts[1].strip()
        extracted = extracted.strip('"').strip("'")
        if len(extracted) > 3:
            return extracted

    # 4. Catch internal nested quote-wrapped questions if the LLM put them inside quotes
    quoted_matches = re.findall(r'""(.*?)""', text)
    if not quoted_matches:
        quoted_matches = re.findall(r'"(.*?)"', text)
    if quoted_matches:
        for match in quoted_matches:
            if "?" in match or "Imagine" in match:
                return match.strip()

    # 5. Clean out explicit multi-line structures like lists and "Input:" blocks
    if "Input:" in text:
        for line in text.split("\n"):
            line = line.strip()
            if "?" in line and not line.lower().startswith("input:"):
                return line.strip('"').strip("'").strip()

    # 6. Strip standard simple inline conversational introductory structures as a fallback
    clean_patterns = [
        r"^Based on the provided context, I will rewrite the input as follows:\s*",
        r"^Based on the provided context, the rewritten input is:\s*",
        r"^Given the input.*the rewritten input is:\s*",
        r"^Given the context.*here\'s a rewritten input.*:\s*",
        r"^I can rewrite it as:\s*",
    ]
    for pattern in clean_patterns:
        text = re.sub(pattern, "", text, flags=re.IGNORECASE | re.DOTALL)

    # 7. Clean up raw literal break line characters and double spaces
    text = text.replace(r"\n\n", " ").replace(r"\n", " ").replace("\n", " ")
    text = re.sub(r"\s+", " ", text).strip()

    # 8. Strip out trailing metadata tags sometimes generated by back-end templates
    text = re.sub(r"-retrieved_knowledge_context\d+$", "", text)

    # 9. Clean out trailing meta-explanations added by the LLM inside the question block
    explanation_patterns = [
        r"(?:This rewritten input|I added the constraint|The rewritten input).*$",
    ]
    for pattern in explanation_patterns:
        text = re.sub(pattern, "", text, flags=re.IGNORECASE | re.DOTALL)

    return text.strip()


# 6. Build, filter, and format dataset safely
test_data = []
for golden in generated_goldens:
    raw_input = golden.input

    if isinstance(raw_input, (tuple, list)):
        raw_input = raw_input[0] if raw_input else ""

    clean_input = clean_extracted_text(raw_input)

    # NEW: Safety check to completely drop rows where the LLM just gave an AI greeting/roleplay response
    ai_greeting_phrases = [
        "ready to act",
        "how can i help",
        "provide the input",
        "i'd be happy to help",
        "what is the input you'd like me to rewrite",
    ]
    if any(phrase in clean_input.lower() for phrase in ai_greeting_phrases):
        print(f'⚠️ Dropped a broken roleplay response row: "{clean_input[:50]}..."')
        continue

    # Skip rows that failed generation checks completely (e.g. meta explanations or empty strings)
    if (
        clean_input.lower().startswith("based on the provided context")
        or len(clean_input) <= 3
    ):
        continue

    test_data.append(
        {
            "input": clean_input,
            "expected_output": golden.expected_output,
            "context": golden.context[0]
            if isinstance(golden.context, list) and golden.context
            else (golden.context or ""),
        }
    )

# 7. Save dataset cleanly
df = pd.DataFrame(test_data)
df.to_csv("adversarial_inputs.csv", index=False)
print(
    f"\n🎉 Success! Compiled {len(df)} pristine adversarial test scenarios into 'adversarial_inputs.csv'"
)
